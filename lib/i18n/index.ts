const CATALOGS: Partial<Record<Locale, Catalog>> = { en, sv };

export type TParams = Record<string, string | number>;

function interpolate(template: string, params?: TParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    key in params ? String(params[key]) : `{${key}}`,
  );
}

/**
 * Translate `key` for `locale`, with `{name}` interpolation. Fallback chain:
 * requested locale → English base → the key itself (never blank).
 */
export function t(locale: Locale, key: TranslationKey, params?: TParams): string {
  const catalog = CATALOGS[locale] ?? CATALOGS[BASE_LOCALE];
  const plural = pluralKey(locale, key, params);
  const template =
    (plural ? catalog?.[plural] : undefined) ??
    catalog?.[key] ??
    (plural ? en[plural] : undefined) ??
    en[key] ??
    key;
  return interpolate(template, params);
}

/**
 * Plural forms (T-309 · review B-42): with a `{count}`, the key's `.one` form is used where the
 * language's plural rule says "one" ("1 free catch"); the key itself is the other form. A count
 * already formatted as text ("1 250") is read back as a number.
 */
function pluralKey(locale: Locale, key: TranslationKey, params?: TParams): TranslationKey | null {
  const raw = params?.count;
  if (raw === undefined) return null;
  const n = typeof raw === 'number' ? raw : Number(String(raw).replace(/[^\d.-]/g, ''));
  if (!Number.isFinite(n)) return null;
  const form = new Intl.PluralRules(locale).select(n);
  return form === 'one' ? (`${key}.one` as TranslationKey) : null;
}

/** Bind a locale once (e.g. per screen): `const tr = createTranslator(locale)`. */
export function createTranslator(locale: Locale) {
  return (key: TranslationKey, params?: TParams): string => t(locale, key, params);
}

