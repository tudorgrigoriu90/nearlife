// One-off generator: turns the sourced photo manifest (pipeline/data/media_kronoberg.json, from
// build_kronoberg_media.py) into the app's typed KRONOBERG_MEDIA, with the deterministic Supabase
// Storage public URL for each photo (bucket 'species-media', key '<speciesId>.<ext>'). The binaries
// are uploaded by pipeline/media/supabase_upload.py; the app reads them from your CDN, never
// Wikimedia. Emits lib/species/media.kronoberg.ts. Run: `npx tsx scripts/gen-kronoberg-media.ts`.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const MEDIA_JSON = join(ROOT, 'pipeline', 'data', 'media_kronoberg.json');
const OUT = join(ROOT, 'lib', 'species', 'media.kronoberg.ts');
const BUCKET = 'species-media';

/** Storage base URL — from env, else parsed from .env.local (the project the app is wired to). */
function supabaseUrl(): string {
  if (process.env.EXPO_PUBLIC_SUPABASE_URL) return process.env.EXPO_PUBLIC_SUPABASE_URL;
  const env = readFileSync(join(ROOT, '.env.local'), 'utf8');
  const m = env.match(/EXPO_PUBLIC_SUPABASE_URL=(.+)/);
  if (!m) throw new Error('EXPO_PUBLIC_SUPABASE_URL not set (env or .env.local)');
  return m[1].trim();
}

interface SourcedMedia {
  speciesId: string;
  imageUrl: string | null;
  appLicense?: string;
  author?: string;
  sourceUrl?: string;
  ext?: string;
}

const base = supabaseUrl().replace(/\/$/, '');
const payload = JSON.parse(readFileSync(MEDIA_JSON, 'utf8')) as { media: SourcedMedia[] };
const withPhoto = payload.media.filter((m) => m.imageUrl && m.appLicense && m.ext);

const rows = withPhoto
  .map((m) => {
    const url = `${base}/storage/v1/object/public/${BUCKET}/${m.speciesId}.${m.ext}`;
    return (
      `  { speciesId: ${JSON.stringify(m.speciesId)}, url: ${JSON.stringify(url)}, ` +
      `license: ${JSON.stringify(m.appLicense)}, author: ${JSON.stringify(m.author ?? 'Unknown')}, ` +
      `sourceUrl: ${JSON.stringify(m.sourceUrl ?? '')}, isPrimary: true },`
    );
  })
  .join('\n');

const out = `// AUTO-GENERATED by scripts/gen-kronoberg-media.ts — do not edit by hand.
// Source: Wikipedia + Wikimedia Commons (commercial-safe licenses only: CC0 / CC-BY / CC-BY-SA).
// Photos are re-hosted on Supabase Storage (bucket '${BUCKET}') by pipeline/media/supabase_upload.py;
// the app reads them from the CDN with a graceful category-emoji fallback until the upload runs.
import type { SpeciesMedia } from './media';

export const KRONOBERG_MEDIA: SpeciesMedia[] = [
${rows}
];
`;

writeFileSync(OUT, out, 'utf8');
console.log(`wrote ${OUT} — ${withPhoto.length}/${payload.media.length} species with a photo`);
