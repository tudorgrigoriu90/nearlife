/* global __dirname */
// Transpile the app's pure push and purchase modules into the Edge Function tree (T-201, T-217).
//
// The `send-notifications` Edge Function runs on Deno, which needs explicit file extensions on
// relative imports; the app's TypeScript uses extensionless ones (Metro/Jest resolve them). Rather
// than duplicate the notification engine in a second codebase, this emits a JS copy of exactly the
// modules the function imports, with specifiers rewritten — using the TypeScript compiler that is
// already a dev dependency, so no bundler is added.
//
// The output is committed (supabase/functions/_shared/lib) because deploys ship that directory.
// __tests__/edgeShared.test.ts regenerates it in memory and fails if the committed copy is stale.
//
//   node scripts/edgeShared.js     # rewrite the committed copy after changing a source module

const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'supabase', 'functions', '_shared', 'lib');
const ENTRIES = ['lib/pushDispatch.ts', 'lib/fcmAuth.ts', 'lib/species/media.ts', 'lib/revenuecatEvents.ts'];

const HEADER =
  '// GENERATED by scripts/edgeShared.js from the app source — do not edit; run `node scripts/edgeShared.js`.\n';

function resolveSource(fromFile, specifier) {
  const base = path.resolve(path.dirname(fromFile), specifier);
  for (const candidate of [`${base}.ts`, path.join(base, 'index.ts')]) {
    if (fs.existsSync(candidate)) return candidate;
  }
  throw new Error(`cannot resolve ${specifier} from ${path.relative(ROOT, fromFile)}`);
}

/** Map of output path (relative to OUT_DIR) → file contents, following runtime imports only. */
function buildEdgeShared() {
  const out = new Map();
  const queue = ENTRIES.map((p) => path.join(ROOT, p));
  const seen = new Set();
  while (queue.length > 0) {
    const file = queue.shift();
    if (seen.has(file)) continue;
    seen.add(file);
    // Type-only imports are erased here, so the walk below sees runtime dependencies only.
    const { outputText } = ts.transpileModule(fs.readFileSync(file, 'utf8'), {
      compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
      fileName: file,
    });
    const rewritten = outputText.replace(/(from\s+['"])(\.{1,2}\/[^'"]+)(['"])/g, (_m, pre, spec, post) => {
      const source = resolveSource(file, spec);
      queue.push(source);
      let rel = path.relative(path.dirname(file), source).replace(/\.ts$/, '.js');
      if (!rel.startsWith('.')) rel = `./${rel}`;
      return `${pre}${rel.split(path.sep).join('/')}${post}`;
    });
    const outRel = path.relative(path.join(ROOT, 'lib'), file).replace(/\.ts$/, '.js');
    out.set(outRel.split(path.sep).join('/'), HEADER + rewritten);
  }
  return out;
}

function writeEdgeShared() {
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  for (const [rel, text] of buildEdgeShared()) {
    const target = path.join(OUT_DIR, rel);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text);
  }
}

module.exports = { buildEdgeShared, OUT_DIR };

if (require.main === module) writeEdgeShared();
