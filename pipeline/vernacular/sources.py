"""Vernacular-name sourcing: everything that decides what counts as a real name (T-159).

Pure functions, no network — the fetching lives in client.py, mirroring gbif/client.py vs
gbif/aggregate.py. That split is what makes the interesting rule testable offline:

    a species with no attested name in a language must produce a GAP, never a guess.

Irish and Maltese are the languages that forced this module to exist. Most of the 54 Kronoberg
species do not occur in Ireland and almost none occur in Malta, so a large share of the list has
no traditional name at all. Coining plausible-sounding ones and shipping them at `machine` status
would put invented names in front of a reader under the same label as the checked ones, which is
exactly what the dual-display picker rule is meant to prevent.
"""

import re

# A parenthesised qualifier on a wiki article title ("Lon dubh (éan)") disambiguates the article,
# not the animal. It is never part of the name a reader would use.
_DISAMBIGUATOR = re.compile(r"\s*\([^)]*\)\s*$")


def _clean(candidate: str) -> str:
    return _DISAMBIGUATOR.sub("", candidate or "").strip()


def _is_real_name(candidate: str, scientific_name: str) -> bool:
    """A candidate is a vernacular name only if it is non-empty and not the binomial itself.

    Both Wikidata and the smaller wikis fall back to the scientific name when no vernacular one
    exists. Accepting that would be the worst outcome available: the reader is told their language
    has a word for this species, and the word is Latin.
    """
    if not candidate:
        return False
    return candidate.casefold() != scientific_name.casefold()


def names_from_sparql(payload: dict) -> dict:
    """{scientific name: vernacular name} from a Wikidata SPARQL result (P1843 bindings).

    First binding wins, so a rerun of the generator produces a byte-identical file rather than
    churning the diff whenever Wikidata's row order shifts.
    """
    out: dict = {}
    for row in payload.get("results", {}).get("bindings", []):
        sci = row.get("sci", {}).get("value", "")
        name = _clean(row.get("name", {}).get("value", ""))
        if sci and sci not in out and _is_real_name(name, sci):
            out[sci] = name
    return out


def names_from_sitelinks(pages: dict) -> dict:
    """{scientific name: vernacular name} from {scientific name: wiki article title}."""
    out: dict = {}
    for sci, title in pages.items():
        name = _clean(title)
        if _is_real_name(name, sci):
            out[sci] = name
    return out


def merge_sources(common_names: dict, article_titles: dict) -> dict:
    """Merge the two sources, preferring an explicit common-name statement.

    P1843 asserts "this IS the vernacular name". An article title merely says where an editor
    filed the page, which on a small wiki is often a translated English phrase rather than a name
    the language actually uses — so it is the fallback, not the primary.
    """
    merged = dict(article_titles)
    merged.update(common_names)
    return merged


def unsourced(species: list, names: dict) -> list:
    """The [(id, scientific name)] entries with no attested name, in input order."""
    return [(sid, sci) for sid, sci in species if sci not in names]


def emit_names_module(locale: str, prefix: str, species: list, names: dict) -> str:
    """Render `lib/species/names.<locale>.ts`, or raise if any species is unsourced.

    Refusing a partial module is deliberate. `contentInLocale` has no English fallback by design
    (T-154) — the mother-tongue half must never quietly show a third language — so a locale that
    is missing names renders blank halves. An absent language is honest; a patchy one is not.
    """
    gaps = unsourced(species, names)
    if gaps:
        listed = ", ".join(sid for sid, _ in gaps)
        raise ValueError(
            f"{locale}: {len(gaps)} of {len(species)} species have no attested name ({listed}). "
            "Refusing to write a partial module — supply these names from a language authority "
            "or leave the locale unregistered."
        )

    lines = [
        f"// {locale} common names for the Kronoberg species (T-159 · F13.3). Unlike the other",
        "// names.*.ts files these are **sourced, not authored**: generated by",
        "// pipeline/build_vernacular_names.py from Wikidata taxon common names (P1843), falling",
        "// back to the language's own Wikipedia article title. Regenerate rather than hand-edit.",
        "// Status `machine`, like every dual-display locale — a labelled reading aid (T-152).",
        "",
        f"export const {prefix}_NAMES: Record<string, string> = {{",
    ]
    for sid, sci in species:
        key = sid if re.fullmatch(r"[A-Za-z_$][\w$]*", sid) else f"'{sid}'"
        value = names[sci].replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  {key}: '{value}',")
    lines.append("};")
    return "\n".join(lines) + "\n"
