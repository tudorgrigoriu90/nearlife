"""Swedish county outlines for on-device hometown resolution (T-090).

The app turns one location fix into a home county *on the phone*, so coordinates never leave the
device (PRIVACY §1). That needs county polygons bundled in the app.

Source: Natural Earth admin-1 (public domain). Not GADM, even though the region ids are GADM's:
GADM's licence forbids commercial use, and bundling its geometry would ship it. Natural Earth is
drawn at 1:10m, so borders are accurate to roughly a kilometre — fine for "which county do you live
in", and the resolver falls back to the nearest county for points just off a simplified coast.

The join to our GADM ids is by county name, never by position in a list: both sources spell the
counties their own way ("Orebro" / "Örebro"), and a positional join that slips by one would put
every user in their neighbour's county while looking perfectly well-formed.
"""

import unicodedata

from gbif.counties import SWEDISH_COUNTIES

# Pinned to a release so a rebuild produces the same file (checked: v5.1.2 == master for Sweden,
# 2026-10-28).
NATURAL_EARTH_URL = (
    "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/"
    "geojson/ne_10m_admin_1_states_provinces.geojson"
)

# 3 decimals ≈ 100 m — an order of magnitude finer than the source's own accuracy.
DECIMALS = 3


def fold(name: str) -> str:
    """Case- and diacritic-insensitive key: 'Örebro' and 'Orebro' meet at 'orebro'."""
    decomposed = unicodedata.normalize("NFKD", name)
    return "".join(c for c in decomposed if not unicodedata.combining(c)).lower().strip()


GID_BY_FOLDED_NAME = {fold(c["name"]): c["gid"] for c in SWEDISH_COUNTIES}


def swedish_features(geojson: dict) -> list:
    return [f for f in geojson["features"] if f["properties"].get("adm0_a3") == "SWE"]


def gid_for(feature: dict) -> str:
    name = feature["properties"]["name"]
    gid = GID_BY_FOLDED_NAME.get(fold(name))
    if gid is None:
        raise ValueError(f"Natural Earth county {name!r} matches no GADM county")
    return gid


def polygons_of(geometry: dict) -> list:
    """Polygon or MultiPolygon → list of polygons (each a list of rings)."""
    if geometry["type"] == "Polygon":
        return [geometry["coordinates"]]
    if geometry["type"] == "MultiPolygon":
        return geometry["coordinates"]
    raise ValueError(f"unexpected geometry type {geometry['type']}")


def round_ring(ring: list, decimals: int = DECIMALS) -> list:
    """Round [lng, lat] points and drop the consecutive duplicates rounding creates."""
    out: list = []
    for lng, lat, *_ in ring:
        point = [round(lng, decimals), round(lat, decimals)]
        if not out or out[-1] != point:
            out.append(point)
    return out


def county_shapes(geojson: dict) -> list:
    """[{gid, name, polygons}] for all 21 counties, sorted by gid; outer rings only.

    Holes are dropped: a Swedish county with a hole is a lake or an enclave, and a point in a lake
    still lives in that county — the hole would only push it to the nearest-county fallback.
    """
    shapes = []
    for feature in swedish_features(geojson):
        gid = gid_for(feature)
        polygons = []
        for polygon in polygons_of(feature["geometry"]):
            outer = round_ring(polygon[0])
            if len(outer) >= 4:  # a closed triangle at least; rounding can collapse a tiny islet
                polygons.append(outer)
        shapes.append({"gid": gid, "polygons": polygons})

    gids = [s["gid"] for s in shapes]
    expected = sorted(c["gid"] for c in SWEDISH_COUNTIES)
    if sorted(gids) != expected:
        missing = sorted(set(expected) - set(gids))
        dupes = sorted({g for g in gids if gids.count(g) > 1})
        raise ValueError(f"county join is not 1:1 — missing {missing}, duplicated {dupes}")
    name_by_gid = {c["gid"]: c["name"] for c in SWEDISH_COUNTIES}
    for s in shapes:
        s["name"] = name_by_gid[s["gid"]]
    return sorted(shapes, key=lambda s: int(s["gid"].split(".")[1].split("_")[0]))


def to_typescript(shapes: list) -> str:
    lines = [
        "// AUTO-GENERATED by pipeline/build_county_shapes.py — do not edit by hand.",
        "// Natural Earth admin-1 v5.1.2 (public domain), joined to GADM ids by county name.",
        "// Outer rings only, [lng, lat] rounded to 3 decimals.",
        "import type { CountyShape } from './countyShape';",
        "",
        "export const SWEDISH_COUNTY_SHAPES: CountyShape[] = [",
    ]
    for s in shapes:
        rings = ",".join(
            "[" + ",".join(f"[{lng:g},{lat:g}]" for lng, lat in ring) + "]" for ring in s["polygons"]
        )
        lines.append(f'  {{ id: "{s["gid"]}", name: "{s["name"]}", polygons: [{rings}] }},')
    lines.append("];")
    return "\n".join(lines) + "\n"
