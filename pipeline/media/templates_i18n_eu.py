"""The 20 EU languages the app offers as a second language (T-231).

Same shape as the entries in templates_i18n.LOCALES, kept in their own file because there are many.
These are conservation and access instructions, general-purpose prose, written here rather than
sourced; they ship labelled machine-translated (T-152). Facts are still sourced per language from
each Wikipedia edition (T-179).

Season phrasing follows each language's grammar instead of a translated English string:
- Where a month inflects after "from"/"to", the three month lists carry the right cases (Polish
  "od maja do września", Finnish "toukokuusta syyskuuhun", Hungarian "májustól szeptemberig").
- A broken run of months is listed in a case-neutral frame where the language would otherwise need
  a case per month ("w miesiącach: maj, lipiec").
- French and Italian elide or add a letter before a vowel ("d'avril", "ad agosto"), so the
  preposition lives inside the month form for those slots.

The sentence pattern refers to "the species" (feminine or neuter in most of these languages), so
the pronoun agrees with the word for species, never with a guessed animal gender.

Irish and Maltese are not here: the app marks them `missing` (lib/i18n/coverage.ts).
"""

def _t(**taxa: tuple[str, str, str]) -> dict[str, dict[str, str]]:
    return {k: {"give": g, "protect": p, "habitat": h} for k, (g, p, h) in taxa.items()}


EU: dict[str, dict] = {}

