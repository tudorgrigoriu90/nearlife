"""The committed presence files obey the season rule (T-268 · review B-04, B-65).

Runs over pipeline/data/presence_*.json as regenerated by the data pipeline, not over fixtures:
it fails if a summer migrant is active in winter in any Swedish county, if any county-month facet
was left capped, or if a record lacks its monthly counts.
"""

import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gbif.aggregate import active_months, migrants_active_in_winter  # noqa: E402

DATA = Path(__file__).resolve().parents[1] / "data"
FILES = sorted(DATA.glob("presence_*.json"))


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def test_there_are_presence_files():
    assert len(FILES) >= 9


@pytest.mark.parametrize("path", FILES, ids=lambda p: p.stem)
def test_no_capped_facet_and_every_record_has_monthly_counts(path):
    data = load(path)
    assert data["meta"].get("facetTruncations", 0) == 0
    assert all(r.get("monthCounts") and len(r["monthCounts"]) == 12 for r in data["records"])


@pytest.mark.parametrize("path", FILES, ids=lambda p: p.stem)
def test_active_months_follow_the_threshold(path):
    for r in load(path)["records"]:
        assert r["activeMonths"] == active_months(r["monthCounts"]), r["scientificName"]


def test_no_summer_migrant_is_active_in_winter_in_any_county():
    birds = load(DATA / "presence_birds.json")["records"]
    swedish = [r for r in birds if r["county"].startswith("SWE.")]
    assert migrants_active_in_winter(swedish) == []
    swift = [r for r in swedish if r["scientificName"] == "Apus apus" and r["county"] == "SWE.9_1"]
    assert swift and 1 not in swift[0]["activeMonths"]
